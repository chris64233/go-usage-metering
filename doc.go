// Package usagemetering 提供带修正记录、结算截点、费率版本与账单草稿的用量计量能力。
//
// 核心模型：
//   - 用量事件（Event）：由外部事件号幂等标识，包含租户、计量项、发生时间与精确数量。
//   - 修正（Correction）：必须引用一条原事件，以有符号增量（delta）记账，永不覆盖历史；
//     同一原事件可以有多次独立修正，修正号本身幂等。
//   - 结算周期（Period）：租户内首尾相接、互不重叠的半开时间区间 [Start, End)。
//   - 快照（Snapshot）：周期关闭时生成，内容不可变；关闭之后才到达的迟到事件或修正
//     不会改写旧快照，而是落到下一个开放周期，作为带来源关联的调整项（Adjustment）。
//   - 费率版本（RateVersion）：按 (租户, 计量项, 生效时间) 发布的不可变费率，
//     含分段价格（PriceTier）与数量/金额计价精度；同一生效时刻至多一份费率，
//     计价时取 effective_from <= 发生时间 的最新版本。
//   - 账单草稿（Draft）：针对已关闭周期生成，生成时冻结周期快照边界、每条用量解析到的
//     费率版本副本与逐条计价明细（DraftLine）。重复生成返回同一草稿；费率后续发布或
//     修订不改写已冻结草稿。草稿可作废并重新生成新版本，旧版本及其明细永久保留，
//     同一周期至多一个当前版本。
//
// 迟到调整（事件或修正）在承载周期的草稿中单列（Adjustment=true），并引用原事件号与
// 原周期起点；其金额一律按“原事件发生时间”的费率版本计价。草稿总额为全部明细金额的
// 精确求和（github.com/shopspring/decimal），恒等于 NormalAmount + AdjustmentAmount。
