// Package usagemetering 提供带修正记录与结算截点的用量计量能力。
//
// 核心模型：
//   - 用量事件（Event）：由外部事件号幂等标识，包含租户、计量项、发生时间与精确数量。
//   - 修正（Correction）：必须引用一条原事件，以有符号增量（delta）记账，永不覆盖历史；
//     同一原事件可以有多次独立修正，修正号本身幂等。
//   - 结算周期（Period）：租户内首尾相接、互不重叠的半开时间区间 [Start, End)。
//   - 快照（Snapshot）：周期关闭时生成，内容不可变；关闭之后才到达的迟到事件或修正
//     不会改写旧快照，而是落到下一个开放周期，作为带来源关联的调整项（Adjustment）。
//
// 002 轮在上述模型上增加费率版本与账单草稿：
//   - 费率版本（RateVersion）：按租户、计量项与生效时间发布，含分段累进价格与计价精度；
//     发布后不可变，同一时刻不允许两份有效费率。某用量按其发生时间选取
//     “生效时间最大且不晚于该时刻”的版本。
//   - 账单草稿（BillVersion）：按周期生成、版本化并整体冻结（周期边界与状态、适用费率副本、
//     逐条计价明细、数量快照、金额合计）。重复生成按幂等键返回同一草稿；费率后来发布或修订、
//     迟到用量都不会改写已冻结草稿。
//   - 作废重算（VoidBill + GenerateBill）：当前版本作废后可生成新版本，旧版本与明细保留；
//     同一周期并发重算时数据库保证只有一个版本成为当前草稿。
//   - 迟到调整计价：顺延到下一周期的迟到修正单列、引用原事件与原周期，金额按“原事件发生时”
//     的费率计算，而不是修正提交或自身业务时间。
//
// 所有数量与金额均使用 github.com/shopspring/decimal 精确计算并以规范文本持久化。
